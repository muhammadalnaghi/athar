package com.athar.core.data.ledger.db

import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase

/**
 * WM028-13B1 schema ownership for the canonical ledger: the 8→9 migration SQL
 * and the revision-singleton seed, kept out of [com.athar.core.data.db.AtharDatabase]
 * so the database class stays inside its 300-line bound.
 *
 * The DDL below must stay byte-for-byte equivalent to what Room generates for
 * the six `canonical_ledger_*` entities (column order, affinity, NOT NULL,
 * composite primary keys, foreign keys, index names). Room's migration
 * validation compares this migrated structure against the KSP-exported
 * schema 9 JSON — the schema export itself is always generated by real KSP,
 * never hand-authored.
 *
 * No destructive statement appears here: migrations 1→8 remain untouched and
 * there is no fallback/reset path.
 */
internal object CanonicalLedgerSchema {

    /** Fixed primary key of the single [CanonicalLedgerRevisionEntity] row. */
    internal const val REVISION_SINGLETON_ID: String = "singleton"

    /**
     * Consistent initialization of the revision metadata singleton, used by
     * both entry points: this migration (migrated databases) and the
     * builder's `onCreate` callback (fresh databases). Plain INSERT — the
     * table is brand new in both paths, so the row can never collide; an
     * already-initialized ledger is never rewritten to zero.
     */
    internal const val SEED_REVISION_SINGLETON_SQL: String =
        "INSERT INTO canonical_ledger_revision (id, revision) VALUES ('$REVISION_SINGLETON_ID', 0)"

    /**
     * v8 → v9: adds the canonical ledger (WM028-13B1) — six internal tables
     * (event, source observation, event↔source association, component, leg,
     * revision metadata) with no changes to any existing table.
     */
    internal val MIGRATION_8_9: Migration = object : Migration(8, 9) {
        override fun migrate(db: SupportSQLiteDatabase) {
            db.execSQL(
                """
                CREATE TABLE IF NOT EXISTS `canonical_ledger_event` (
                    `eventId` TEXT NOT NULL,
                    `economicIdentityIssuer` TEXT,
                    `economicIdentityReference` TEXT,
                    `snapshotFormatVersion` INTEGER NOT NULL,
                    `policyRevision` TEXT NOT NULL,
                    `graphRevision` TEXT NOT NULL,
                    `snapshotJson` TEXT NOT NULL,
                    `bookedAmount` TEXT NOT NULL,
                    `bookedCurrency` TEXT NOT NULL,
                    `bookedBasis` TEXT NOT NULL,
                    `kind` TEXT NOT NULL,
                    `kindResolved` INTEGER NOT NULL,
                    `incomeNature` TEXT NOT NULL,
                    `recordingOutcome` TEXT NOT NULL,
                    `eventDate` TEXT,
                    `routing` TEXT NOT NULL,
                    `composition` TEXT NOT NULL,
                    PRIMARY KEY(`eventId`)
                )
                """.trimIndent(),
            )
            db.execSQL(
                """
                CREATE UNIQUE INDEX IF NOT EXISTS
                `index_canonical_ledger_event_economicIdentityIssuer_economicIdentityReference`
                ON `canonical_ledger_event` (`economicIdentityIssuer`, `economicIdentityReference`)
                """.trimIndent(),
            )
            db.execSQL(
                """
                CREATE TABLE IF NOT EXISTS `canonical_ledger_source_observation` (
                    `sourceNamespace` TEXT NOT NULL,
                    `sourceId` TEXT NOT NULL,
                    `evidenceRef` TEXT,
                    `payloadDigest` TEXT,
                    PRIMARY KEY(`sourceNamespace`, `sourceId`)
                )
                """.trimIndent(),
            )
            db.execSQL(
                """
                CREATE TABLE IF NOT EXISTS `canonical_ledger_event_source` (
                    `sourceNamespace` TEXT NOT NULL,
                    `sourceId` TEXT NOT NULL,
                    `eventId` TEXT NOT NULL,
                    PRIMARY KEY(`sourceNamespace`, `sourceId`),
                    FOREIGN KEY(`sourceNamespace`, `sourceId`)
                        REFERENCES `canonical_ledger_source_observation`(`sourceNamespace`, `sourceId`)
                        ON UPDATE NO ACTION ON DELETE NO ACTION,
                    FOREIGN KEY(`eventId`)
                        REFERENCES `canonical_ledger_event`(`eventId`)
                        ON UPDATE NO ACTION ON DELETE NO ACTION
                )
                """.trimIndent(),
            )
            db.execSQL(
                """
                CREATE INDEX IF NOT EXISTS `index_canonical_ledger_event_source_eventId`
                ON `canonical_ledger_event_source` (`eventId`)
                """.trimIndent(),
            )
            db.execSQL(
                """
                CREATE TABLE IF NOT EXISTS `canonical_ledger_component` (
                    `eventId` TEXT NOT NULL,
                    `componentRef` TEXT NOT NULL,
                    `type` TEXT NOT NULL,
                    `amount` TEXT NOT NULL,
                    `currency` TEXT NOT NULL,
                    `feeRelation` TEXT,
                    `feeEvidenceRef` TEXT,
                    PRIMARY KEY(`eventId`, `componentRef`),
                    FOREIGN KEY(`eventId`)
                        REFERENCES `canonical_ledger_event`(`eventId`)
                        ON UPDATE NO ACTION ON DELETE NO ACTION
                )
                """.trimIndent(),
            )
            db.execSQL(
                """
                CREATE INDEX IF NOT EXISTS `index_canonical_ledger_component_eventId`
                ON `canonical_ledger_component` (`eventId`)
                """.trimIndent(),
            )
            db.execSQL(
                """
                CREATE TABLE IF NOT EXISTS `canonical_ledger_leg` (
                    `eventId` TEXT NOT NULL,
                    `legRef` TEXT NOT NULL,
                    `accountRef` TEXT NOT NULL,
                    `delta` TEXT NOT NULL,
                    `currency` TEXT NOT NULL,
                    `componentRef` TEXT,
                    PRIMARY KEY(`eventId`, `legRef`),
                    FOREIGN KEY(`eventId`)
                        REFERENCES `canonical_ledger_event`(`eventId`)
                        ON UPDATE NO ACTION ON DELETE NO ACTION,
                    FOREIGN KEY(`eventId`, `componentRef`)
                        REFERENCES `canonical_ledger_component`(`eventId`, `componentRef`)
                        ON UPDATE NO ACTION ON DELETE NO ACTION,
                    FOREIGN KEY(`accountRef`)
                        REFERENCES `account`(`id`)
                        ON UPDATE NO ACTION ON DELETE NO ACTION
                )
                """.trimIndent(),
            )
            db.execSQL(
                """
                CREATE INDEX IF NOT EXISTS `index_canonical_ledger_leg_accountRef`
                ON `canonical_ledger_leg` (`accountRef`)
                """.trimIndent(),
            )
            db.execSQL(
                """
                CREATE INDEX IF NOT EXISTS `index_canonical_ledger_leg_eventId_componentRef`
                ON `canonical_ledger_leg` (`eventId`, `componentRef`)
                """.trimIndent(),
            )
            db.execSQL(
                """
                CREATE TABLE IF NOT EXISTS `canonical_ledger_revision` (
                    `id` TEXT NOT NULL,
                    `revision` INTEGER NOT NULL,
                    PRIMARY KEY(`id`)
                )
                """.trimIndent(),
            )
            db.execSQL(SEED_REVISION_SINGLETON_SQL)
        }
    }
}
